import { cleanup } from '@testing-library/react';
import '@testing-library/jest-dom';

declare global {
  var IntersectionObserver: typeof IntersectionObserver;
}

// Cleanup after each test
afterEach(() => {
  cleanup();
});

// Mock window.matchMedia
